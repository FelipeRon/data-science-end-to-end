-- Ejecutar una vez en Snowsight con los roles administrativos correspondientes.
-- No modifica tablas existentes ni claves del usuario existente.
USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS PSET2_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;
CREATE DATABASE IF NOT EXISTS PSET2_MANTENIMIENTO;
CREATE SCHEMA IF NOT EXISTS PSET2_MANTENIMIENTO.RAW;
CREATE SCHEMA IF NOT EXISTS PSET2_MANTENIMIENTO.BRONZE;
CREATE SCHEMA IF NOT EXISTS PSET2_MANTENIMIENTO.SILVER;
CREATE SCHEMA IF NOT EXISTS PSET2_MANTENIMIENTO.GOLD;
CREATE SCHEMA IF NOT EXISTS PSET2_MANTENIMIENTO.OBT;

USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS PSET2_INGEST;
GRANT ROLE PSET2_INGEST TO USER PSET2_KESTRA;
GRANT USAGE ON WAREHOUSE PSET2_WH TO ROLE PSET2_INGEST;
GRANT USAGE, CREATE SCHEMA ON DATABASE PSET2_MANTENIMIENTO TO ROLE PSET2_INGEST;
GRANT USAGE ON ALL SCHEMAS IN DATABASE PSET2_MANTENIMIENTO TO ROLE PSET2_INGEST;
GRANT CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT
  ON ALL SCHEMAS IN DATABASE PSET2_MANTENIMIENTO TO ROLE PSET2_INGEST;
-- El rol crea y posee las nuevas tablas del pipeline. No necesita ACCOUNTADMIN.
-- Si PSET2_KESTRA aún no existe, crearlo y registrar su clave pública por separado.


